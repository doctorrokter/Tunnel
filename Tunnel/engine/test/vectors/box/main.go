// Command box prints kat_box.h: NaCl box and secretbox vectors for engine/test/test_salsa.c.
//
// Tailscale's DERP seals ClientInfo and opens ServerInfo with key.NodePrivate.SealTo / OpenFrom
// (tailscale v1.102.5, types/key/node.go; callers in derp/derp_client.go and
// derp/derpserver/derpserver.go). Those are box.Seal / box.Open from golang.org/x/crypto/nacl/box
// behind a random 24-byte nonce. This program calls exactly those functions - from the x/crypto
// version tailscale pins (its go.mod: v0.54.0, pinned the same in ours) - with fixed keys and
// nonces, so the C side is checked byte for byte against the reference, not against itself.
//
// It also reproduces the classic NaCl example from "Cryptography in NaCl" (D. J. Bernstein), as
// libsodium 1.0.20 carries it in test/default/{core1,core2,stream3,onetimeauth,box,box2}.c, and
// the Poly1305 example of RFC 8439 section 2.5.2, and it stops if Go disagrees with either.
//
// Regenerate only when the inputs change:
//
//	cd engine/test/vectors/box && go run -buildvcs=false . > ../kat_box.h
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"runtime/debug"
	"strings"

	"golang.org/x/crypto/curve25519"
	"golang.org/x/crypto/nacl/box"
	"golang.org/x/crypto/nacl/secretbox"
	"golang.org/x/crypto/poly1305"
	"golang.org/x/crypto/salsa20"
	"golang.org/x/crypto/salsa20/salsa"
)

// The message lengths every box and secretbox vector is made for: empty, around the 32 bytes that
// ride in block 0 of the stream after the Poly1305 key, around the next block, and a long one.
var lengths = []int{0, 1, 31, 32, 33, 63, 64, 65, 1000}

// clientInfo and serverInfo mirror derp.ClientInfo (derp/derp_client.go) and derp.ServerInfo
// (derp/derp.go) with their JSON tags. MeshKey (json "meshKey,omitzero") is left out: a regular
// client never sets it, and a zero one is not marshalled.
type clientInfo struct {
	Version     int `json:"version,omitempty"`
	CanAckPings bool
	IsProber    bool   `json:",omitempty"`
	AppName     string `json:",omitempty"`
}

type serverInfo struct {
	Version                   int `json:"version,omitempty"`
	TokenBucketBytesPerSecond int `json:",omitempty"`
	TokenBucketBytesBurst     int `json:",omitempty"`
}

// derpProtocolVersion is derp.ProtocolVersion (derp/derp.go).
const derpProtocolVersion = 2

func main() {
	var out bytes.Buffer
	w := &out

	fmt.Fprintf(w, `/*
 * Generated by test/vectors/box (Go, golang.org/x/crypto %s) - do not edit, rerun it:
 *     cd engine/test/vectors/box && go run -buildvcs=false . > ../kat_box.h
 *
 * Every box and secretbox below comes out of golang.org/x/crypto/nacl/box and nacl/secretbox,
 * the functions behind Tailscale's key.NodePrivate.SealTo / OpenFrom (DERP ClientInfo and
 * ServerInfo). Layout as crypto_box_easy: Poly1305 tag (16), then the ciphertext.
 */

#ifndef KAT_BOX_H
#define KAT_BOX_H

#include <stddef.h>

`, cryptoVersion())

	classic(w)
	rfc8439(w)
	golang(w)

	fmt.Fprintf(w, "#endif /* KAT_BOX_H */\n")
	os.Stdout.Write(out.Bytes())
}

// classic is the example of "Cryptography in NaCl": Alice (the RFC 7748 keys) boxes 131 bytes to
// Bob. Each stage has its own published value, so a mismatch in C points at one primitive.
func classic(w *bytes.Buffer) {
	aliceSK := unhex32("77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a")
	bobSK := unhex32("5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb")
	nonce := unhex24("69696ee955b62b73cd62bda875fc73d68219e0036b7a0b37")
	msg := unhex("be075fc53c81f2d5cf141316ebeb0c7b5228c52a4c62cbd44b66849b64244ffc" +
		"e5ecbaaf33bd751a1ac728d45e6c61296cdc3c01233561f41db66cce314adb31" +
		"0e3be8250c46f06dceea3a7fa1348057e2f6556ad6b1318a024a838f21af1fde" +
		"048977eb48f59ffd4924ca1c60902e52f0a089bc76897040e082f93776384864" +
		"5e0705")
	// The published outputs (libsodium test/default/*.exp).
	wantAlicePK := unhex("8520f0098930a754748b7ddcb43ef75a0dbf3a0d26381af4eba4a98eaa9b4e6a")
	wantBobPK := unhex("de9edb7d7b7dc1b4d35b61c2ece435373f8343c85b78674dadfc7e146f882b4f")
	wantShared := unhex("4a5d9d5ba4ce2de1728e3bf480350f25e07e21c947d19e3376f09b3c1e161742")
	wantFirst := unhex("1b27556473e985d462cd51197a9a46c76009549eac6474f206c4ee0844f68389")
	wantSecond := unhex("dc908dda0b9344a953629b733820778880f3ceb421bb61b91cbd4c3e66256ce4")
	wantRS := unhex("eea6a7251c1e72916d11c2cb214d3c252539121d8e234e652d651fa4c8cff880")
	wantBox := unhex("f3ffc7703f9400e52a7dfb4b3d3305d98e993b9f48681273c29650ba32fc76ce" +
		"48332ea7164d96a4476fb8c531a1186ac0dfc17c98dce87b4da7f011ec48c972" +
		"71d2c20f9b928fe2270d6fb863d51738b48eeee314a7cc8ab932164548e526ae" +
		"90224368517acfeabd6bb3732bc0e9da99832b61ca01b6de56244a9e88d5f9b3" +
		"7973f622a43d14a6599b1f654cb45a74e355a5")
	// libsodium box.c: a point of small order - crypto_box must refuse it, and so must we.
	smallOrder := unhex("e0eb7a7c3b41b8ae1656e3faf19fc46ada098deb9c32b1fd866205165f49b800")

	var alicePK, bobPK, shared, first, second, zero32 [32]byte
	curve25519.ScalarBaseMult(&alicePK, &aliceSK)
	curve25519.ScalarBaseMult(&bobPK, &bobSK)
	sh, err := curve25519.X25519(aliceSK[:], bobPK[:])
	check(err == nil, "X25519 alice/bob")
	copy(shared[:], sh)
	box.Precompute(&first, &bobPK, &aliceSK)
	var in16 [16]byte
	copy(in16[:], nonce[:16])
	salsa.HSalsa20(&second, &in16, &first, &salsa.Sigma)
	var rs [32]byte
	salsa20.XORKeyStream(rs[:], zero32[:], nonce[:], &first)
	var tag [16]byte
	poly1305.Sum(&tag, wantBox[16:], &rs)
	sealed := box.Seal(nil, msg, &nonce, &bobPK, &aliceSK)
	opened, ok := box.Open(nil, sealed, &nonce, &alicePK, &bobSK)

	check(bytes.Equal(alicePK[:], wantAlicePK), "alice pk")
	check(bytes.Equal(bobPK[:], wantBobPK), "bob pk")
	check(bytes.Equal(shared[:], wantShared), "shared secret (RFC 7748 6.1)")
	check(bytes.Equal(first[:], wantFirst), "core1: beforenm")
	check(bytes.Equal(second[:], wantSecond), "core2: HSalsa20")
	check(bytes.Equal(rs[:], wantRS), "stream3: XSalsa20")
	check(bytes.Equal(tag[:], wantBox[:16]), "onetimeauth: Poly1305")
	check(bytes.Equal(sealed, wantBox), "box")
	check(ok && bytes.Equal(opened, msg), "box2: open")

	fmt.Fprintf(w, `/*
 * The classic example of "Cryptography in NaCl" (D. J. Bernstein), stage by stage, as libsodium
 * 1.0.20 publishes it in test/default: core1.c (beforenm = HSalsa20 of the X25519 secret),
 * core2.c (the XSalsa20 subkey), stream3.c (the first 32 stream bytes = the Poly1305 key),
 * onetimeauth.c (the tag), box.c / box2.c (the box, less NaCl's 16 zero bytes). The keys are
 * RFC 7748's. golang.org/x/crypto reproduces every value - the generator checks.
 */
`)
	str(w, "KAT_NACL_ALICE_SK", aliceSK[:])
	str(w, "KAT_NACL_ALICE_PK", alicePK[:])
	str(w, "KAT_NACL_BOB_SK", bobSK[:])
	str(w, "KAT_NACL_BOB_PK", bobPK[:])
	str(w, "KAT_NACL_SHARED", shared[:])
	str(w, "KAT_NACL_FIRSTKEY", first[:])
	str(w, "KAT_NACL_NONCE", nonce[:])
	str(w, "KAT_NACL_SECONDKEY", second[:])
	str(w, "KAT_NACL_RS", rs[:])
	str(w, "KAT_NACL_MSG", msg)
	str(w, "KAT_NACL_BOX", sealed)
	fmt.Fprintf(w, "/* libsodium box.c: a public key of small order; crypto_box_beforenm refuses it */\n")
	str(w, "KAT_NACL_SMALL_ORDER", smallOrder)
	fmt.Fprintln(w)
}

// rfc8439 is the Poly1305 example of RFC 8439 section 2.5.2.
func rfc8439(w *bytes.Buffer) {
	key := unhex32("85d6be7857556d337f4452fe42d506a80103808afb0db2fd4abff6af4149f51b")
	msg := []byte("Cryptographic Forum Research Group")
	want := unhex("a8061dc1305136c6c22b8baf0c0127a9")

	var tag [16]byte
	poly1305.Sum(&tag, msg, &key)
	check(bytes.Equal(tag[:], want), "RFC 8439 2.5.2")

	fmt.Fprintf(w, "/* RFC 8439 section 2.5.2: Poly1305 of \"%s\" */\n", msg)
	str(w, "KAT_POLY1305_KEY", key[:])
	str(w, "KAT_POLY1305_MSG", msg)
	str(w, "KAT_POLY1305_TAG", tag[:])
	fmt.Fprintln(w)
}

// golang is the main set: fixed keys and nonces through box.Seal and secretbox.Seal.
func golang(w *bytes.Buffer) {
	// Node keys as key.NewNode stores them: 32 bytes, clamped (types/key/node.go).
	clientSK, serverSK := fixed("client node key"), fixed("server node key")
	clamp(&clientSK)
	clamp(&serverSK)
	var clientPK, serverPK, k, k2 [32]byte
	curve25519.ScalarBaseMult(&clientPK, &clientSK)
	curve25519.ScalarBaseMult(&serverPK, &serverSK)
	box.Precompute(&k, &serverPK, &clientSK)
	box.Precompute(&k2, &clientPK, &serverSK)
	check(k == k2, "beforenm is symmetric")

	boxNonce := nonce24("box nonce")
	sbKey := fixed("secretbox key")
	sbNonce := nonce24("secretbox nonce")

	msg := make([]byte, 0, 1024)
	for i := 0; len(msg) < 1000; i++ {
		h := sha256.Sum256([]byte(fmt.Sprintf("tunnel kat_box: message block %d", i)))
		msg = append(msg, h[:]...)
	}
	msg = msg[:1000]

	stream := make([]byte, 200)
	salsa20.XORKeyStream(stream, make([]byte, len(stream)), sbNonce[:], &sbKey)

	fmt.Fprintf(w, `/*
 * golang.org/x/crypto with fixed inputs. The node keys are clamped, as key.NewNode stores them;
 * the client seals to the server as DERP's ClientInfo does (box.Seal(msg, nonce, server_pk,
 * client_sk)). Keys, nonces and the message are SHA-256 of labels - nothing up the sleeve.
 */
`)
	str(w, "KAT_BOX_CLIENT_SK", clientSK[:])
	str(w, "KAT_BOX_CLIENT_PK", clientPK[:])
	str(w, "KAT_BOX_SERVER_SK", serverSK[:])
	str(w, "KAT_BOX_SERVER_PK", serverPK[:])
	fmt.Fprintf(w, "/* box.Precompute(server_pk, client_sk) == box.Precompute(client_pk, server_sk) */\n")
	str(w, "KAT_BOX_BEFORENM", k[:])
	str(w, "KAT_BOX_NONCE", boxNonce[:])
	str(w, "KAT_SECRETBOX_KEY", sbKey[:])
	str(w, "KAT_SECRETBOX_NONCE", sbNonce[:])
	fmt.Fprintf(w, "/* salsa20.XORKeyStream over 200 zero bytes with the 24-byte KAT_SECRETBOX_NONCE (XSalsa20) */\n")
	str(w, "KAT_XSALSA20_STREAM", stream)
	fmt.Fprintf(w, "/* The vectors below seal the first `len` bytes of this */\n")
	str(w, "KAT_BOX_MSG", msg)

	fmt.Fprintf(w, `
typedef struct {
    size_t len;
    const char* secretbox;  /* secretbox.Seal(msg[:len], KAT_SECRETBOX_NONCE, KAT_SECRETBOX_KEY) */
    const char* box;        /* box.Seal(msg[:len], KAT_BOX_NONCE, server_pk, client_sk) */
} kat_box_vec;

static const kat_box_vec KAT_BOX_VECS[] = {
`)
	for _, n := range lengths {
		m := msg[:n]
		sb := secretbox.Seal(nil, m, &sbNonce, &sbKey)
		bx := box.Seal(nil, m, &boxNonce, &serverPK, &clientSK)
		check(len(sb) == n+secretbox.Overhead && len(bx) == n+box.Overhead, "lengths")
		back, ok := secretbox.Open(nil, sb, &sbNonce, &sbKey)
		check(ok && bytes.Equal(back, m), "secretbox.Open")
		// The server opens what the client sealed, as recvClientKey does.
		back, ok = box.Open(nil, bx, &boxNonce, &clientPK, &serverSK)
		check(ok && bytes.Equal(back, m), "box.Open")
		back, ok = box.OpenAfterPrecomputation(nil, bx, &boxNonce, &k)
		check(ok && bytes.Equal(back, m), "box.OpenAfterPrecomputation")

		fmt.Fprintf(w, "    { %d,\n", n)
		fmt.Fprintf(w, "%s,\n", lines(sb, "      "))
		fmt.Fprintf(w, "%s },\n", lines(bx, "      "))
	}
	fmt.Fprintf(w, "};\n\n")

	// DERP: the payloads a real client and server exchange, sealed the way SealTo does it -
	// box.Seal appending to the nonce - with fixed nonces instead of random ones.
	ci, err := json.Marshal(clientInfo{Version: derpProtocolVersion, CanAckPings: true})
	check(err == nil, "marshal ClientInfo")
	si, err := json.Marshal(serverInfo{Version: derpProtocolVersion})
	check(err == nil, "marshal ServerInfo")
	ciNonce, siNonce := nonce24("ClientInfo nonce"), nonce24("ServerInfo nonce")
	ciSealed := box.Seal(ciNonce[:], ci, &ciNonce, &serverPK, &clientSK)
	siSealed := box.Seal(siNonce[:], si, &siNonce, &clientPK, &serverSK)
	back, ok := box.Open(nil, ciSealed[24:], &ciNonce, &clientPK, &serverSK)
	check(ok && bytes.Equal(back, ci), "server opens ClientInfo")
	back, ok = box.Open(nil, siSealed[24:], &siNonce, &serverPK, &clientSK)
	check(ok && bytes.Equal(back, si), "client opens ServerInfo")

	fmt.Fprintf(w, `/*
 * DERP. ClientInfo as tailscaled sends it (magicsock sets CanAckPings) and ServerInfo as derper
 * answers it (derpserver.go sendServerInfo), each sealed as SealTo returns it: nonce (24) || box.
 * The FrameClientInfo payload is the client's public key followed by this. Two nonces: beforenm
 * is symmetric, so the directions must not share one.
 */
`)
	cstr(w, "KAT_DERP_CLIENT_INFO", ci)
	str(w, "KAT_DERP_CLIENT_INFO_SEALED", ciSealed)
	cstr(w, "KAT_DERP_SERVER_INFO", si)
	str(w, "KAT_DERP_SERVER_INFO_SEALED", siSealed)
	fmt.Fprintln(w)
}

// fixed derives 32 bytes from a label.
func fixed(label string) [32]byte { return sha256.Sum256([]byte("tunnel kat_box: " + label)) }

func nonce24(label string) (n [24]byte) {
	h := fixed(label)
	copy(n[:], h[:])
	return n
}

// clamp is clamp25519Private of types/key/node.go.
func clamp(k *[32]byte) {
	k[0] &= 248
	k[31] = (k[31] & 127) | 64
}

func cryptoVersion() string {
	if bi, ok := debug.ReadBuildInfo(); ok {
		for _, d := range bi.Deps {
			if d.Path == "golang.org/x/crypto" {
				return d.Version
			}
		}
	}
	panic("golang.org/x/crypto is not in the build info")
}

// str prints a hex string literal, 32 bytes a line, the way kat_noise.h does.
func str(w *bytes.Buffer, name string, b []byte) {
	fmt.Fprintf(w, "static const char %s[] =\n%s;\n", name, lines(b, "    "))
}

func lines(b []byte, indent string) string {
	h := hex.EncodeToString(b)
	if h == "" {
		return indent + `""`
	}
	var parts []string
	for len(h) > 64 {
		parts = append(parts, indent+`"`+h[:64]+`"`)
		h = h[64:]
	}
	parts = append(parts, indent+`"`+h+`"`)
	return strings.Join(parts, "\n")
}

// cstr prints printable ASCII as a C string literal.
func cstr(w *bytes.Buffer, name string, b []byte) {
	var s strings.Builder
	for _, c := range b {
		check(c >= 0x20 && c < 0x7f, "printable ASCII")
		if c == '"' || c == '\\' {
			s.WriteByte('\\')
		}
		s.WriteByte(c)
	}
	fmt.Fprintf(w, "static const char %s[] = \"%s\";\n", name, s.String())
}

func unhex(s string) []byte {
	b, err := hex.DecodeString(s)
	check(err == nil, "hex "+s)
	return b
}

func unhex32(s string) (k [32]byte) {
	b := unhex(s)
	check(len(b) == 32, "32 bytes: "+s)
	copy(k[:], b)
	return k
}

func unhex24(s string) (n [24]byte) {
	b := unhex(s)
	check(len(b) == 24, "24 bytes: "+s)
	copy(n[:], b)
	return n
}

func check(ok bool, what string) {
	if !ok {
		fmt.Fprintf(os.Stderr, "gen: %s: mismatch\n", what)
		os.Exit(1)
	}
}
